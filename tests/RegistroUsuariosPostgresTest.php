    private function verificarError(
        array $resultado,
        string $mensaje
    ): void {
        self::assertFalse($resultado['valido']);

        self::assertContains(
            $mensaje,
            array_column(
                $resultado['errores'],
                'mensaje'
            )
        );
    }

    private function prepararImportacion(
        array $datos
    ): array {
        $resultado = $this->validar($datos);

        self::assertTrue(
            $resultado['valido'],
            json_encode(
                $resultado['errores'],
                JSON_UNESCAPED_UNICODE
            )
        );

        foreach ($resultado['usuarios'] as &$usuario) {

            $usuario['password_hash'] = password_hash(
                $usuario['password'],
                PASSWORD_DEFAULT
            );

            unset($usuario['password']);
        }

        unset($usuario);

        $resultado['aulas_snapshot'] =
            $this->pdo->query("
                SELECT id, nombre, asignatura_nombre
                FROM aulas
                WHERE colegio_id = 1
                  AND activo = TRUE
                ORDER BY id
            ")->fetchAll();

        return $resultado;
    }

    private function contarUsuarios(): int
    {
        return (int) $this->pdo->query(
            'SELECT COUNT(*) FROM usuarios'
        )->fetchColumn();
    }

    private function contarTabla(string $tabla): int
    {
        if (!in_array($tabla, [
            'usuarios',
            'aula_alumnos',
            'aula_profesores',
            'apoderado_estudiantes'
        ], true)) {
            throw new LogicException('Tabla incorrecta.');
        }

        return (int) $this->pdo->query(
            'SELECT COUNT(*) FROM ' . $tabla
        )->fetchColumn();
    }

    private function comprobarRollback(
        array $datos,
        string $mensaje,
        int $adminId = 1
    ): void {
        $antes = $this->contarUsuarios();

        try {
            importarUsuariosRegistro(
                $this->pdo,
                1,
                $adminId,
                $datos
            );

            self::fail(
                'La importación debía ser rechazada.'
            );

        } catch (InvalidArgumentException $e) {

            self::assertSame(
                $mensaje,
                $e->getMessage()
            );
        }

        self::assertFalse(
            $this->pdo->inTransaction()
        );

        self::assertSame(
            $antes,
            $this->contarUsuarios()
        );

        self::assertSame(
            0,
            $this->contarTabla('aula_alumnos')
        );

        self::assertSame(
            0,
            $this->contarTabla('aula_profesores')
        );

        self::assertSame(
            0,
            $this->contarTabla('apoderado_estudiantes')
        );
    }

