    private PDO $pdo;
    private string $schema;

    protected function setUp(): void
    {
        $dsn = getenv('US05_TEST_DSN');

        if (!$dsn) {
            $this->markTestSkipped(
                'Requiere PostgreSQL desechable us05_test.'
            );
        }

        $this->pdo = new PDO(
            $dsn,
            getenv('US05_TEST_USER') ?: 'postgres',
            getenv('US05_TEST_PASSWORD') ?: null,
            [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC
            ]
        );

        if (
            $this->pdo->query(
                'SELECT current_database()'
            )->fetchColumn() !== 'us05_test'
        ) {
            throw new RuntimeException(
                'Base de datos de pruebas incorrecta.'
            );
        }

        $this->schema = 'registro_' . bin2hex(random_bytes(6));

        $this->pdo->exec(
            'CREATE SCHEMA ' . $this->schema
        );

        $this->pdo->exec(
            'SET search_path TO ' . $this->schema
        );

        $this->pdo->exec("
            CREATE TABLE usuarios (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                colegio_id INTEGER NOT NULL,
                rut TEXT NOT NULL UNIQUE,
                username TEXT NOT NULL UNIQUE,
                nombre TEXT NOT NULL,
                apellido TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                rol TEXT NOT NULL CHECK (
                    rol IN (
                        'admin',
                        'alumno',
                        'profesor',
                        'apoderado'
                    )
                ),
                activo BOOLEAN NOT NULL DEFAULT TRUE
            );

            CREATE TABLE aulas (
                id INTEGER PRIMARY KEY,
                colegio_id INTEGER NOT NULL,
                nombre TEXT NOT NULL,
                asignatura_nombre TEXT,
                activo BOOLEAN NOT NULL DEFAULT TRUE
            );

            CREATE TABLE aula_alumnos (
                aula_id INTEGER REFERENCES aulas(id),
                alumno_id INTEGER REFERENCES usuarios(id),
                PRIMARY KEY (aula_id, alumno_id)
            );

            CREATE TABLE aula_profesores (
                aula_id INTEGER REFERENCES aulas(id),
                profesor_id INTEGER REFERENCES usuarios(id),
                PRIMARY KEY (aula_id, profesor_id)
            );

            CREATE TABLE apoderado_estudiantes (
                colegio_id INTEGER NOT NULL,
                apoderado_id INTEGER REFERENCES usuarios(id),
                estudiante_id INTEGER REFERENCES usuarios(id),
                estado TEXT NOT NULL,
                confirmada_en TIMESTAMPTZ,
                confirmada_por INTEGER REFERENCES usuarios(id),
                PRIMARY KEY (apoderado_id, estudiante_id)
            );
        ");

        $this->pdo->exec("
            INSERT INTO usuarios (
                colegio_id,
                rut,
                username,
                nombre,
                apellido,
                password_hash,
                rol,
                activo
            ) VALUES
                (
                    1, '10000004-0', 'admin.prueba',
                    'Admin', 'Uno', 'fixture',
                    'admin', TRUE
                ),
                (
                    2, '10000013-K', 'admin.ajeno',
                    'Admin', 'Dos', 'fixture',
                    'admin', TRUE
                ),
                (
                    1, '1234567-4', 'alumno.existente',
                    'Alumno', 'Existente', 'fixture',
                    'alumno', TRUE
                ),
                (
                    1, '90000001-1', 'admin.inactivo',
                    'Admin', 'Inactivo', 'fixture',
                    'admin', FALSE
                ),
                (
                    2, '11111111-1', 'alumno.ajeno',
                    'Alumno', 'Ajeno', 'fixture',
                    'alumno', TRUE
                );

            INSERT INTO aulas VALUES
                (10, 1, '8 Básico A', 'Matemáticas', TRUE),
                (11, 1, '8 Básico A', 'Lenguaje', TRUE),
                (12, 1, '8 Básico B', 'Ciencias', TRUE),
                (13, 1, '7 Básico A', 'Historia', FALSE),
                (14, 2, '4 Medio A', 'Física', TRUE);
        ");
    }

    protected function tearDown(): void
    {
        if (isset($this->pdo, $this->schema)) {

            if ($this->pdo->inTransaction()) {
                $this->pdo->rollBack();
            }

            $this->pdo->exec(
                'SET search_path TO public'
            );

            $this->pdo->exec(
                'DROP SCHEMA ' . $this->schema . ' CASCADE'
            );
        }
    }

