            '12345678-5',
            $usuario['rut']
        );

        self::assertTrue(
            password_verify(
                'Clave12345',
                $usuario['password_hash']
            )
        );

        self::assertSame(
            2,
            $this->contarTabla('aula_alumnos')
        );

        self::assertFalse(
            $this->pdo->inTransaction()
        );
    }

