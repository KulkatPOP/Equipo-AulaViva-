    }
    public static function duplicados(): array { return [['rut'],['username']]; }
    #[DataProvider('duplicados')]
    public function testDuplicadoNoConsumeInvitacion(string $campo): void
    {
        $rut=$campo==='rut'?'alumno-prueba':'otro-rut'; $username=$campo==='username'?'alumno-prueba':'otro-usuario';
        $this->pdo->prepare("INSERT INTO usuarios(colegio_id,rut,username,nombre,apellido,password_hash,rol) VALUES (2,?,?,'Otro','Prueba','fixture','alumno')")->execute([$rut,$username]);
        $this->rechazar(409,fn()=>activarInvitacion($this->pdo,$this->hash,$this->datos()));
        self::assertSame(2,(int)$this->pdo->query('SELECT count(*) FROM usuarios')->fetchColumn());
        self::assertSame(0,(int)$this->pdo->query('SELECT count(*) FROM invitaciones WHERE usado')->fetchColumn());
