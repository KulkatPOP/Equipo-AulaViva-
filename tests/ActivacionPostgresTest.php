<?php
declare(strict_types=1);

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
require_once __DIR__ . '/../config/activacion.php';

final class ActivacionPostgresTest extends TestCase
{
    private PDO $pdo;
    private string $schema;
    private string $token;
    private string $hash;
    private $servidor = null;
    private ?string $cookie = null;
    private int $puerto;

    protected function setUp(): void
    {
        $dsn = getenv('ACTIVACION_TEST_DSN');
        if (!$dsn) { $this->markTestSkipped('Requiere base PostgreSQL desechable activacion_test y ACTIVACION_TEST_DSN.'); }
        $this->pdo = new PDO($dsn, getenv('ACTIVACION_TEST_USER') ?: 'postgres', getenv('ACTIVACION_TEST_PASSWORD') ?: null,
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        if ($this->pdo->query('SELECT current_database()')->fetchColumn() !== 'activacion_test') {
            throw new RuntimeException('Solo se permiten pruebas sobre activacion_test.');
        }
        $this->schema = 'activacion_' . bin2hex(random_bytes(6));
        $this->pdo->exec('CREATE SCHEMA ' . $this->schema);
        $this->pdo->exec('SET search_path TO ' . $this->schema);
        $this->pdo->exec("CREATE TABLE usuarios (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            colegio_id integer NOT NULL, rut text NOT NULL UNIQUE, username text NOT NULL UNIQUE,
            nombre text NOT NULL, apellido text NOT NULL, password_hash text NOT NULL,
            rol text NOT NULL CHECK (rol IN ('alumno','profesor','admin','apoderado')),
            activo boolean NOT NULL DEFAULT TRUE, UNIQUE(id,colegio_id));");
        $this->pdo->exec(file_get_contents(__DIR__ . '/../migrations/006_invitaciones.sql'));
        $this->pdo->exec("INSERT INTO usuarios(id,colegio_id,rut,username,nombre,apellido,password_hash,rol)
            VALUES (10,1,'docente-prueba','docente-prueba','Docente','Prueba','fixture','profesor')");
        $this->token = str_repeat('a', 64);
        $this->hash = hash('sha256', $this->token);
        $stmt = $this->pdo->prepare("INSERT INTO invitaciones(colegio_id,email,rut,username,token_hash,rol,expira_en,idempotency_key)
            VALUES (1,'alumno@example.test','alumno-prueba','alumno-prueba',?,'alumno',clock_timestamp()+interval '1 hour','prueba-activacion')");
        $stmt->execute([$this->hash]);
    }

    protected function tearDown(): void
    {
        if (is_resource($this->servidor)) { proc_terminate($this->servidor); proc_close($this->servidor); }
        if ($this->cookie !== null) { @unlink($this->cookie); }
        if (isset($this->pdo,$this->schema)) {
            if ($this->pdo->inTransaction()) { $this->pdo->rollBack(); }
            $this->pdo->exec('SET search_path TO public');
            $this->pdo->exec('DROP SCHEMA ' . $this->schema . ' CASCADE');
        }
    }

    private function datos(): array
    {
        return ['nombre'=>'Ana','apellido'=>'Prueba','password'=>'Solo-Prueba-2026!','confirmar_password'=>'Solo-Prueba-2026!'];
    }

    private function estadoSinActivar(): void
    {
        self::assertSame(1,(int)$this->pdo->query('SELECT count(*) FROM usuarios')->fetchColumn());
        self::assertSame(0,(int)$this->pdo->query('SELECT count(*) FROM invitaciones WHERE usado=TRUE')->fetchColumn());
        self::assertFalse($this->pdo->inTransaction());
    }

    private function rechazar(int $estado, callable $accion): void
    {
        try { $accion(); self::fail('La operación debía rechazarse.'); }
        catch (ErrorActivacion $e) { self::assertSame($estado,$e->estadoHttp); }
    }

    public static function rolesValidos(): array { return [['alumno'],['profesor']]; }

    #[DataProvider('rolesValidos')]
    public function testActivacionCreaCuentaConIdentidadOriginal(string $rol): void
    {
        $this->pdo->prepare('UPDATE invitaciones SET rol=?')->execute([$rol]);
        $datos = $this->datos() + ['colegio_id'=>999,'rol'=>'admin','username'=>'otro','rut'=>'otro','token_hash'=>str_repeat('f',64)];
        $id = activarInvitacion($this->pdo,$this->hash,$datos);
        $stmt=$this->pdo->prepare('SELECT * FROM usuarios WHERE id=?'); $stmt->execute([$id]); $u=$stmt->fetch(PDO::FETCH_ASSOC);
        self::assertSame(1,(int)$u['colegio_id']); self::assertSame($rol,$u['rol']);
        self::assertSame('alumno-prueba',$u['username']); self::assertSame('alumno-prueba',$u['rut']);
        self::assertTrue(password_verify($datos['password'],$u['password_hash']));
        self::assertNotSame($datos['password'],$u['password_hash']);
        self::assertSame(1,(int)$this->pdo->query('SELECT count(*) FROM invitaciones WHERE usado')->fetchColumn());
        self::assertFalse($this->pdo->inTransaction());
    }

    public function testTokenInexistente(): void
    {
        $this->rechazar(400,fn()=>activarInvitacion($this->pdo,str_repeat('0',64),$this->datos()));
        $this->estadoSinActivar();
    }
    public function testTokenVencido(): void
    {
        $this->pdo->exec("UPDATE invitaciones SET expira_en=clock_timestamp()-interval '1 second'");
        $this->rechazar(410,fn()=>activarInvitacion($this->pdo,$this->hash,$this->datos())); $this->estadoSinActivar();
    }
    public function testTokenUtilizadoNoSeReutiliza(): void
    {
        activarInvitacion($this->pdo,$this->hash,$this->datos());
        $this->rechazar(410,fn()=>activarInvitacion($this->pdo,$this->hash,$this->datos()));
        self::assertSame(2,(int)$this->pdo->query('SELECT count(*) FROM usuarios')->fetchColumn());
    }
    public function testColegioSinRespaldoInstitucionalNoSeActiva(): void
    {
        $this->pdo->exec('UPDATE invitaciones SET colegio_id=99');
        $this->rechazar(400,fn()=>activarInvitacion($this->pdo,$this->hash,$this->datos())); $this->estadoSinActivar();
    }

    public static function passwordsInvalidos(): array
    {
