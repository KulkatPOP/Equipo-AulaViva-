        $this->pdo->exec("CREATE FUNCTION fallar_consumo() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RAISE EXCEPTION ''fallo ficticio''; END';
            CREATE TRIGGER fallo_consumo BEFORE UPDATE ON invitaciones FOR EACH ROW EXECUTE FUNCTION fallar_consumo();");
        $this->rechazar(500,fn()=>activarInvitacion($this->pdo,$this->hash,$this->datos())); $this->estadoSinActivar();
    }
    public function testExpiracionDuranteActivacionRevierteUsuario(): void
    {
        $this->pdo->exec("CREATE FUNCTION vencer_al_crear() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN UPDATE invitaciones SET expira_en=clock_timestamp()-interval ''1 second''; RETURN NEW; END';
            CREATE TRIGGER vencer_al_crear BEFORE INSERT ON usuarios FOR EACH ROW EXECUTE FUNCTION vencer_al_crear();");
        $this->rechazar(410,fn()=>activarInvitacion($this->pdo,$this->hash,$this->datos())); $this->estadoSinActivar();
    }

    private function entorno(): array
    {
        $env=getenv();$env['DB_DSN']=getenv('ACTIVACION_TEST_DSN');$env['DB_USER']=getenv('ACTIVACION_TEST_USER')?:'postgres';
        $env['DB_PASSWORD']=getenv('ACTIVACION_TEST_PASSWORD')?:'';$env['PGOPTIONS']='-c search_path='.$this->schema;
        return $env;
    }
    private function servidor(): void
    {
        $this->puerto=random_int(20000,45000);$env=$this->entorno();
        $this->servidor=proc_open([PHP_BINARY,'-S','127.0.0.1:'.$this->puerto,'-t',dirname(__DIR__)],
            [0=>['pipe','r'],1=>['file',(PHP_OS_FAMILY === 'Windows' ? 'NUL' : '/dev/null'),'a'],2=>['file',(PHP_OS_FAMILY === 'Windows' ? 'NUL' : '/dev/null'),'a']],$pipes,null,$env);
        if (!is_resource($this->servidor)) { throw new RuntimeException('No inició el servidor desechable'); }
        fclose($pipes[0]); $this->cookie=tempnam(sys_get_temp_dir(),'activacion-cookie-');
        for($i=0;$i<50;$i++) { $s=@fsockopen('127.0.0.1',$this->puerto,$errno,$err,.1); if($s) { fclose($s);return; } usleep(50000); }
        throw new RuntimeException('No inició el servidor desechable');
    }
    private function http(string $path,?array $datos=null): array
    {
        $curl=curl_init('http://127.0.0.1:'.$this->puerto.'/'.$path);
        curl_setopt_array($curl,[CURLOPT_RETURNTRANSFER=>true,CURLOPT_COOKIEFILE=>$this->cookie,CURLOPT_COOKIEJAR=>$this->cookie,CURLOPT_TIMEOUT=>10]);
        if($datos!==null) { curl_setopt_array($curl,[CURLOPT_POST=>true,CURLOPT_POSTFIELDS=>http_build_query($datos)]); }
        $body=curl_exec($curl);$status=curl_getinfo($curl,CURLINFO_RESPONSE_CODE);$location=curl_getinfo($curl,CURLINFO_REDIRECT_URL);unset($curl);
        return [$status,$body,$location];
    }
    private function formulario(): string
    {
        [$status,$body]=$this->http('activar_cuenta.php?token='.$this->token);self::assertSame(200,$status);
        self::assertStringContainsString('action="activar_cuenta.php"',$body);
        self::assertStringContainsString('alumno-prueba',$body);
        preg_match('/name="csrf_token" value="([^"]+)"/',$body,$m);self::assertArrayHasKey(1,$m);
        return $m[1];
    }
    public function testHttpActivaYPermiteLoginConIdentidadOriginal(): void
    {
        $this->servidor();$csrf=$this->formulario();
        $datos=$this->datos()+['csrf_token'=>$csrf,'username'=>'atacante','rut'=>'otro','colegio_id'=>2,'rol'=>'admin'];
        [$status,,$location]=$this->http('activar_cuenta.php',$datos);
        self::assertSame(303,$status);self::assertStringEndsWith('/login.php',$location);
        [$status,$body]=$this->http('login.php');self::assertSame(200,$status);
        preg_match('/name="csrf_token" value="([^"]+)"/',$body,$m);
        [$status,,$location]=$this->http('login.php',['csrf_token'=>$m[1],'identificador'=>'alumno-prueba','password'=>$datos['password']]);
        self::assertSame(302,$status);self::assertStringEndsWith('/mis_cursos.php',$location);
        self::assertSame(410,$this->http('activar_cuenta.php?token='.$this->token)[0]);
    }
    public function testHttpCsrfInvalidoNoActiva(): void
    {
        $this->servidor();$this->formulario();
        [$status,$body]=$this->http('activar_cuenta.php',$this->datos()+['csrf_token'=>'incorrecto']);
        self::assertSame(403,$status);self::assertStringNotContainsString($this->token,$body);$this->estadoSinActivar();
    }
    public function testHttpTokenInexistenteVencidoUsadoYMalformado(): void
    {
        $this->servidor();
        foreach(['activar_cuenta.php','activar_cuenta.php?token[]=a','activar_cuenta.php?token=abc','activar_cuenta.php?token='.str_repeat('b',64)] as $path) {
            self::assertSame(400,$this->http($path)[0]);
        }
        $this->pdo->exec("UPDATE invitaciones SET expira_en=clock_timestamp()-interval '1 second'");
        self::assertSame(410,$this->http('activar_cuenta.php?token='.$this->token)[0]);
        $this->pdo->exec("UPDATE invitaciones SET usado=TRUE,expira_en=clock_timestamp()+interval '1 hour'");
        self::assertSame(410,$this->http('activar_cuenta.php?token='.$this->token)[0]);
    }

    public function testDosActivacionesConcurrentesSoloUnaConsumeToken(): void
    {
        $archivo=tempnam(sys_get_temp_dir(),'activacion-worker-');$archivos=[$archivo];$procesos=[];
        $config=var_export(dirname(__DIR__).'/config/activacion.php',true);
        file_put_contents($archivo,'<?php require '.$config.';
            $pdo=new PDO(getenv("DB_DSN"),getenv("DB_USER"),getenv("DB_PASSWORD")?:null,[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION]);
            $pdo->exec("SET statement_timeout = 30000");
            $pdo->prepare("SELECT set_config(\'application_name\',?,false)")->execute([getenv("WORKER_NAME")]);
            file_put_contents(getenv("WORKER_READY"),"ready");
            try { activarInvitacion($pdo,hash("sha256",str_repeat("a",64)),["nombre"=>"Ana","apellido"=>"Prueba","password"=>"Solo-Prueba-2026!","confirmar_password"=>"Solo-Prueba-2026!"]);echo json_encode(["status"=>303]); }
            catch(ErrorActivacion $e) { echo json_encode(["status"=>$e->estadoHttp]); }');
        try {
            $this->pdo->beginTransaction();$this->pdo->query('SELECT id FROM invitaciones FOR UPDATE')->fetchAll();
            $prefijo='activacion-race-'.bin2hex(random_bytes(4));
            for($i=0;$i<2;$i++) {
                $ready=tempnam(sys_get_temp_dir(),'activacion-ready-');$archivos[]=$ready;$env=$this->entorno();$env['WORKER_READY']=$ready;$env['WORKER_NAME']=$prefijo.'-'.$i;
                $proceso=proc_open([PHP_BINARY,$archivo],[0=>['pipe','r'],1=>['pipe','w'],2=>['pipe','w']],$pipes,null,$env);
                if(!is_resource($proceso)) { throw new RuntimeException('No inició el proceso concurrente'); }
                fclose($pipes[0]);$procesos[]=[$proceso,$pipes];
            }
            $consulta=$this->pdo->prepare("SELECT count(*) FROM pg_stat_activity WHERE application_name LIKE ? AND wait_event_type='Lock'");
            $bloqueados=0;$limite=microtime(true)+20;
            while(microtime(true)<$limite) {
                $this->pdo->query('SELECT pg_stat_clear_snapshot()');
                $consulta->execute([$prefijo.'%']);$bloqueados=(int)$consulta->fetchColumn();
                if($bloqueados===2) { break; } usleep(20000);
            }
            self::assertSame(2,$bloqueados,'Ambos procesos deben competir por el bloqueo de la misma invitación');
            $this->pdo->commit();$estados=[];
            foreach($procesos as [$proceso,$pipes]) {
                $salida=stream_get_contents($pipes[1]);$error=stream_get_contents($pipes[2]);
                self::assertSame('',$error);$json=json_decode($salida,true,512,JSON_THROW_ON_ERROR);$estados[]=$json['status'];
            }
            sort($estados);self::assertSame([303,410],$estados);
            self::assertSame(1,(int)$this->pdo->query("SELECT count(*) FROM usuarios WHERE username='alumno-prueba'")->fetchColumn());
            self::assertSame(1,(int)$this->pdo->query('SELECT count(*) FROM invitaciones WHERE usado=TRUE')->fetchColumn());
        } finally {
            if($this->pdo->inTransaction()) { $this->pdo->rollBack(); }
            foreach($procesos as [$proceso,$pipes]) { fclose($pipes[1]);fclose($pipes[2]);proc_terminate($proceso);proc_close($proceso); }
            foreach($archivos as $path) { @unlink($path); }
        }
    }
