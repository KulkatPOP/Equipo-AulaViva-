    public function testRollbackSiFallaCrearUsuario(): void
    {
        $this->pdo->exec("CREATE FUNCTION fallar_usuario() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RAISE EXCEPTION ''fallo ficticio''; END';
            CREATE TRIGGER fallo_usuario BEFORE INSERT ON usuarios FOR EACH ROW EXECUTE FUNCTION fallar_usuario();");
