BEGIN;

CREATE TABLE ajustes_notas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    libro_nota_id INTEGER NOT NULL,
    aula_id INTEGER NOT NULL,
    estudiante_id INTEGER NOT NULL,

    tipo TEXT NOT NULL DEFAULT 'automatica'
        CHECK (tipo = 'automatica'),

    calificacion NUMERIC(2,1) NOT NULL
        CHECK (calificacion BETWEEN 1.0 AND 7.0),

    registrado_por INTEGER NOT NULL
        REFERENCES usuarios(id),

    actualizado_por INTEGER NOT NULL
        REFERENCES usuarios(id),

    creado_en TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ajustes_notas_estudiante_unique
        UNIQUE (libro_nota_id, estudiante_id),

    CONSTRAINT ajustes_notas_libro_aula_fk
        FOREIGN KEY (libro_nota_id, aula_id)
        REFERENCES libro_notas(id, aula_id),

    CONSTRAINT ajustes_notas_alumno_aula_fk
        FOREIGN KEY (aula_id, estudiante_id)
        REFERENCES aula_alumnos(aula_id, alumno_id),

    CONSTRAINT ajustes_notas_tipo_fk
        FOREIGN KEY (libro_nota_id, tipo)
        REFERENCES libro_notas(id, tipo)
);

CREATE INDEX ajustes_notas_estudiante_idx
    ON ajustes_notas(estudiante_id);

COMMIT;