-- Initial schema for an EMPTY AulaViva database. Run once before 001-006.
-- Requires PostgreSQL with pgvector already installed on the server and an
-- operator authorized to enable it. Does not install packages, roles or data.
-- Intentionally fails on existing tables rather than accepting an unknown schema.
BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colegio_id integer NOT NULL,
    rut text NOT NULL UNIQUE,
    username text NOT NULL UNIQUE,
    nombre text NOT NULL,
    apellido text NOT NULL,
    password_hash text NOT NULL,
    -- 005 replaces this CHECK and adds apoderado and the composite UNIQUE.
    rol text NOT NULL CHECK (rol IN ('profesor', 'alumno', 'admin')),
    activo boolean NOT NULL DEFAULT true
);

CREATE TABLE aulas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colegio_id integer NOT NULL,
    nombre text NOT NULL,
    activo boolean NOT NULL DEFAULT true
);

CREATE TABLE aula_profesores (
    aula_id integer NOT NULL REFERENCES aulas(id),
    profesor_id integer NOT NULL REFERENCES usuarios(id),
    PRIMARY KEY (aula_id, profesor_id)
);

CREATE TABLE aula_alumnos (
    aula_id integer NOT NULL REFERENCES aulas(id),
    alumno_id integer NOT NULL REFERENCES usuarios(id),
    PRIMARY KEY (aula_id, alumno_id)
);

COMMIT;
