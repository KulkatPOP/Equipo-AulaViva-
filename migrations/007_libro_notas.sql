BEGIN;

-- =========================================
-- LIBRO DE NOTAS
-- =========================================

CREATE TABLE libro_notas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    aula_id INTEGER NOT NULL
        REFERENCES aulas(id),

    numero INTEGER NOT NULL
        CHECK (numero > 0),

    titulo TEXT NOT NULL
        CHECK (btrim(titulo) <> ''),

    tipo TEXT NOT NULL DEFAULT 'manual'
        CHECK (tipo IN ('manual', 'automatica')),

    evaluacion_id UUID
        REFERENCES evaluaciones(id),

    creado_por INTEGER NOT NULL
        REFERENCES usuarios(id),

    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT libro_notas_numero_unique
        UNIQUE (aula_id, numero),

    CONSTRAINT libro_notas_evaluacion_unique
        UNIQUE (evaluacion_id),

    CONSTRAINT libro_notas_id_aula_unique
        UNIQUE (id, aula_id),

    CONSTRAINT libro_notas_tipo_unique
        UNIQUE (id, tipo),

    CONSTRAINT libro_notas_origen_check
        CHECK (
            (tipo = 'manual' AND evaluacion_id IS NULL)
            OR
            (tipo = 'automatica' AND evaluacion_id IS NOT NULL)
        )
    );

-- Garantizar que la evaluación pertenezca
-- a la misma aula del libro de notas.

ALTER TABLE evaluaciones
    ADD CONSTRAINT evaluaciones_id_aula_unique
    UNIQUE (id, aula_id);

ALTER TABLE libro_notas
    ADD CONSTRAINT libro_notas_evaluacion_aula_fk
    FOREIGN KEY (evaluacion_id, aula_id)
    REFERENCES evaluaciones(id, aula_id);


-- =========================================
-- CALIFICACIONES MANUALES
-- =========================================

CREATE TABLE notas_manuales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    libro_nota_id INTEGER NOT NULL,

    aula_id INTEGER NOT NULL,

    estudiante_id INTEGER NOT NULL,

    tipo TEXT NOT NULL DEFAULT 'manual'
        CHECK (tipo = 'manual'),

    calificacion NUMERIC(2,1) NOT NULL
        CHECK (calificacion BETWEEN 1.0 AND 7.0),

    registrado_por INTEGER NOT NULL
        REFERENCES usuarios(id),

    actualizado_por INTEGER NOT NULL
        REFERENCES usuarios(id),

    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT notas_manuales_estudiante_unique
        UNIQUE (libro_nota_id, estudiante_id),

    CONSTRAINT notas_manuales_libro_aula_fk
        FOREIGN KEY (libro_nota_id, aula_id)
        REFERENCES libro_notas(id, aula_id),

    CONSTRAINT notas_manuales_alumno_aula_fk
        FOREIGN KEY (aula_id, estudiante_id)
        REFERENCES aula_alumnos(aula_id, alumno_id),

    CONSTRAINT notas_manuales_tipo_fk
        FOREIGN KEY (libro_nota_id, tipo)
        REFERENCES libro_notas(id, tipo)
);

CREATE INDEX notas_manuales_estudiante_idx
    ON notas_manuales(estudiante_id);

COMMIT;