-- Contrato ya utilizado por POST /api/v1/invitaciones/ y activar_cuenta.php.
-- Ejecutar solo si no existe la tabla; no sustituye esquemas preexistentes.
CREATE TABLE invitaciones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colegio_id integer NOT NULL CHECK (colegio_id > 0),
    email text NOT NULL CHECK (btrim(email) <> ''),
    rut text NOT NULL CHECK (btrim(rut) <> ''),
    username text NOT NULL CHECK (btrim(username) <> ''),
    token_hash text NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    rol text NOT NULL CHECK (rol IN ('alumno', 'profesor')),
    expira_en timestamptz NOT NULL,
    usado boolean NOT NULL DEFAULT FALSE,
    idempotency_key text,
    CHECK (idempotency_key IS NULL OR char_length(idempotency_key) BETWEEN 1 AND 100),
    UNIQUE (colegio_id, idempotency_key)
);
CREATE INDEX invitaciones_activas_email_idx
    ON invitaciones(colegio_id, email, expira_en) WHERE usado = FALSE;

COMMIT;
